    public static String getMimeType(String url) {
        String type = "*/*";
        String extension = MimeTypeMap.getFileExtensionFromUrl(url);
        if (extension != null) {
            type = MimeTypeMap.getSingleton().getMimeTypeFromExtension(extension);
        } else {
            type = "*/*";
        }
        try {
            if (type == null || !type.contains("/")) {
                type = "*/*";
            }
        } catch (Exception e) {
            type = "*/*";
        }
        return type;
    }

